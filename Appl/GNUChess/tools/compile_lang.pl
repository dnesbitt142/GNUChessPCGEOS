#!/usr/bin/env perl
# SPDX-License-Identifier: GPL-3.0-or-later
# Pack or unpack the single map block of a GNU Chess GEOS 2.x language VM.
use strict;
use warnings;
use Encode qw(encode decode FB_CROAK LEAVE_SRC);
use FindBin qw($Bin);

sub read_file {
    my ($name) = @_;
    open my $file, '<:raw', $name or die "$name: $!\n";
    local $/;
    return scalar <$file>;
}

my ($mode, $source, $target) = @ARGV;
die "usage: perl compile_lang.pl pack|unpack|embed input output\n"
    unless @ARGV == 3 && ($mode eq 'pack' || $mode eq 'unpack' || $mode eq 'embed');
my @keys = read_file("$Bin/../language.goh") =~ /^\s+GCT_([A-Z_]+),$/mg;
my $head_size = 2 * (3 + @keys);
my $id = 0x4743;
my $data;

if ($mode ne 'unpack') {
    my %text;
    for (split /\r?\n/, decode('UTF-8', read_file($source), FB_CROAK)) {
        next if /^\s*(?:#|$)/;
        my ($key, $value) = /^([A-Z_]+)=(.+)$/;
        die "Invalid or duplicate catalog entry: $_\n"
            unless defined $key && !exists $text{$key};
        $text{$key} = $value;
    }
    my ($strings, @offsets) = ('');
    for my $key (@keys) {
        my $value = delete $text{$key};
        die "Missing entry $key\n" unless defined $value;
        if ($key =~ /_(?:TURN|CHECK)$/) {
            die "$key must contain %d and %m\n" unless $value =~ /%d/ && $value =~ /%m/;
        }
        my $bytes = encode('MacRoman', $value, FB_CROAK);
        die "Invalid length or control character in $key\n"
            if length($bytes) > 119 || $bytes =~ /[\x00-\x1f\x7f]/;
        die "PIECES must have exactly 12 letters\n"
            if $key eq 'PIECES' && length($bytes) != 12;
        push @offsets, $head_size + length($strings);
        $strings .= "$bytes\0";
    }
    die "Unknown catalog entries: ", join(', ', sort keys %text), "\n" if %text;
    my $map_size = $head_size + length($strings);
    my $map = pack('v*', 1, scalar @keys, $map_size, @offsets) . $strings;

    if ($mode eq 'embed') {
        my @words = unpack('v*', $map . ("\0" x ($map_size % 2)));
        $data = "/* Generated by compile_lang.pl embed from the German catalog. */\n";
        $data .= "static const word GermanCatalog[] = {\n";
        while (@words) {
            $data .= '    ' . join(', ', map { sprintf('0x%04x', $_) }
                                        splice(@words, 0, 8)) . ",\n";
        }
        $data .= "};\n";
    } else {
        # GEOS offsets are relative to the end of the 256-byte GEOS 2.x file
        # header. The 24-byte VM extension is followed by the map and VM table.
        # See Tools/include/os90File.h and Tools/utils/vmInt.h in the SDK.
        my $map_pos = 24;
        my $header_pos = $map_pos + $map_size;
        my $header_size = 56;  # 32-byte header and two 12-byte block handles
        my $file_header = pack('a4a36v', "\xc7E\xc1S", 'GNUCHESS.VM', 2);
        $file_header .= "\0" x (256 - length($file_header));
        my $vm_header = pack('vvVx16', 0xadeb, $header_size, $header_pos);
        my $table = pack('v12VCCv',
            0xfb, 0, 0, 0, $header_size, 0, 0, 2, 0, 0, 44, 70,
            $header_size + $map_size, 0, 0, 0);
        $table .= pack('vCCvvV', 0, 0xff, 0, 0, $header_size, $header_pos);
        $table .= pack('vCCvvV', 0, 0xff, 0, $id, $map_size, $map_pos);
        $data = $file_header . $vm_header . $map . $table;
    }
} else {
    my $vm = read_file($source);
    die "Invalid GEOS VM file\n" unless substr($vm, 0, 4) eq "\xc7E\xc1S";
    my ($signature, $size, $pos) = unpack('vvV', substr($vm, 256, 8));
    my $table = substr($vm, 256 + $pos, $size);
    die "Invalid VM header\n" unless $signature == 0xadeb && length($table) == $size
        && $size >= 56 && unpack('v', $table) == 0xfb;
    my $handle = unpack('v', substr($table, 20, 2));
    die "Invalid map handle\n" if $handle < 44 || $handle + 12 > $size || ($handle - 32) % 12;
    my ($used, $user_id, $map_size, $map_pos) = unpack('x2CxvvV', substr($table, $handle, 12));
    my $map = substr($vm, 256 + $map_pos, $map_size);
    die "Missing GNU Chess language map\n" unless $used == 0xff && $user_id == $id
        && length($map) == $map_size && $map_size >= $head_size;
    my ($version, $count, $size_used, @offsets) = unpack('v*', substr($map, 0, $head_size));
    die "Incompatible catalog version or invalid payload size\n"
        unless $version == 1 && $count == @keys && $size_used == $map_size;
    my $cursor = $head_size;
    my $text = '';
    for my $key (@keys) {
        my $end = index($map, "\0", $cursor);
        die "Invalid catalog entry $key\n" unless shift(@offsets) == $cursor && $end > $cursor;
        $text .= "$key=" . decode('MacRoman', substr($map, $cursor, $end - $cursor),
                                   FB_CROAK | LEAVE_SRC) . "\n";
        $cursor = $end + 1;
    }
    die "Unexpected trailing catalog data\n" unless $cursor == $map_size;
    $data = encode('UTF-8', $text);
}

open my $out, '>:raw', $target or die "$target: $!\n";
print {$out} $data or die "$target: $!\n";
close $out or die "$target: $!\n";
